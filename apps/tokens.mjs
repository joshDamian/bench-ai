#!/usr/bin/env node
// Writes the native clients' theme files from the web's stylesheets, so the eleven themes
// have one source: web/app.css (Classic, in :root) and web/themes.css (the rest).
//
//   node apps/tokens.mjs          write both files
//   node apps/tokens.mjs --check  exit 1 if either file is stale (CI runs this)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const css = (p) => read(p).replace(/\/\*[\s\S]*?\*\//g, '');

// The tokens a native screen draws with. Anything else in the stylesheet is web-only.
const TOKENS = ['bg', 'surface-sunken', 'surface-1', 'surface-2', 'surface-3', 'surface-rail', 'text', 'muted', 'accent', 'on-accent', 'line', 'line-strong', 'good', 'warn', 'bad', 'info', 'dot-idle', 'well-bg', 'well-text'];

/** @param {string} css @param {string} selector */
function block(css, selector) {
  const i = css.indexOf(selector);
  if (i < 0) throw new Error(`No ${selector}`);
  const open = css.indexOf('{', i);
  let depth = 0;
  for (let j = open; j < css.length; j++) {
    if (css[j] === '{') depth++;
    else if (css[j] === '}' && --depth === 0) return css.slice(open + 1, j);
  }
  throw new Error(`Unclosed ${selector}`);
}

/** @param {string} body */
function vars(body) {
  const out = {};
  for (const m of body.matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/g)) out[m[1]] = m[2].trim();
  return out;
}

/** '#abc', '#aabbcc' or 'rgba(r,g,b,a)' as 0xAARRGGBB. */
function argb(v) {
  let m = /^#([0-9a-f]{3})$/i.exec(v);
  if (m) v = '#' + [...m[1]].map((c) => c + c).join('');
  m = /^#([0-9a-f]{6})$/i.exec(v);
  if (m) return 0xff000000 + parseInt(m[1], 16);
  m = /^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)$/i.exec(v);
  if (m) {
    const a = Math.round(255 * (m[4] === undefined ? 1 : Number(m[4])));
    return a * 2 ** 24 + (Number(m[1]) << 16) + (Number(m[2]) << 8) + Number(m[3]);
  }
  throw new Error(`Not a colour: ${v}`);
}

const appCss = css('web/app.css');
const themesCss = css('web/themes.css');
const classic = vars(block(appCss, ':root{'));
const list = read('web/theme.mjs');
const themes = [...list.matchAll(/\{\s*id:\s*'([^']+)',\s*name:\s*'([^']+)',\s*dark:\s*(true|false)/g)].map(([, id, name, dark]) => {
  const own = id === 'classic' ? {} : vars(block(themesCss, `:root[data-theme="${id}"]{`));
  const merged = { ...classic, ...own };
  // Classic leaves these to the stylesheet's var() fallbacks; the same fallbacks here.
  const FALLBACK = { 'dot-idle': 'muted', 'well-bg': 'surface-sunken', 'well-text': 'text' };
  const colors = Object.fromEntries(TOKENS.map((t) => [t, argb(merged[t] ?? merged[FALLBACK[t]])]));
  return { id, name, dark: dark === 'true', colors, radius: parseFloat(merged.radius) || 10, radiusSm: parseFloat(merged['radius-sm']) || 6 };
});
if (themes.length < 2) throw new Error('Read too few themes from web/theme.mjs');

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const hex = (n) => '0x' + n.toString(16).toUpperCase().padStart(8, '0');
const head = 'Generated by apps/tokens.mjs from web/app.css and web/themes.css. Do not edit; change the stylesheet and run `node apps/tokens.mjs`.';

const kotlin = `// ${head}
package ai.bench.app.ui.theme

import androidx.compose.ui.graphics.Color

data class BenchColors(
${TOKENS.map((t) => `    val ${camel(t)}: Color,`).join('\n')}
)

data class BenchThemeSpec(val id: String, val name: String, val dark: Boolean, val radius: Float, val radiusSm: Float, val colors: BenchColors)

val BenchThemes: List<BenchThemeSpec> = listOf(
${themes
  .map(
    (t) => `    BenchThemeSpec(
        "${t.id}", "${t.name}", ${t.dark}, ${t.radius}f, ${t.radiusSm}f,
        BenchColors(
${TOKENS.map((k) => `            ${camel(k)} = Color(${hex(t.colors[k])}),`).join('\n')}
        ),
    ),`
  )
  .join('\n')}
)
`;

const swiftColor = (n) => {
  const a = Math.floor(n / 2 ** 24) / 255;
  const r = ((n >> 16) & 255) / 255;
  const g = ((n >> 8) & 255) / 255;
  const b = (n & 255) / 255;
  const f = (x) => Number(x.toFixed(4));
  return `Color(.sRGB, red: ${f(r)}, green: ${f(g)}, blue: ${f(b)}, opacity: ${f(a)})`;
};

const swift = `// ${head}
import SwiftUI

struct BenchColors {
${TOKENS.map((t) => `    let ${camel(t)}: Color`).join('\n')}
}

struct BenchThemeSpec: Identifiable {
    let id: String
    let name: String
    let dark: Bool
    let radius: CGFloat
    let radiusSm: CGFloat
    let colors: BenchColors
}

let benchThemes: [BenchThemeSpec] = [
${themes
  .map(
    (t) => `    BenchThemeSpec(
        id: "${t.id}", name: "${t.name}", dark: ${t.dark}, radius: ${t.radius}, radiusSm: ${t.radiusSm},
        colors: BenchColors(
${TOKENS.map((k, i) => `            ${camel(k)}: ${swiftColor(t.colors[k])}${i === TOKENS.length - 1 ? '' : ','}`).join('\n')}
        )
    ),`
  )
  .join('\n')}
]
`;

const outputs = [
  ['apps/android/app/src/main/java/ai/bench/app/ui/theme/Tokens.kt', kotlin],
  ['apps/macos/Bench/Theme/Tokens.swift', swift],
];
const check = process.argv.includes('--check');
let stale = 0;
for (const [p, text] of outputs) {
  const file = path.join(root, p);
  const now = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (now === text) continue;
  if (check) {
    console.error(`${p} is stale: run node apps/tokens.mjs`);
    stale++;
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    console.log(`wrote ${p} (${themes.length} themes)`);
  }
}
process.exit(stale ? 1 : 0);
